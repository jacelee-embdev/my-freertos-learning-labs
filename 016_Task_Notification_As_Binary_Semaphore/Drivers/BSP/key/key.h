#ifndef __KEY_H__
#define __KEY_H__

#include "sys.h"

/* ---------------------------------------------------------------------------------- */
/* [硬件移植区] 集中放置底层硬件相关的宏定义，便于跨平台移植或改板                    */
/* ---------------------------------------------------------------------------------- */
#define KEY_PORT                GPIOA                           // 按键所在 GPIO 端口
#define KEY1_PIN                GPIO_PIN_0                      // 按键 1 引脚
#define KEY2_PIN                GPIO_PIN_1                      // 按键 2 引脚
#define KEY_PORT_CLK_ENABLE()   __HAL_RCC_GPIOA_CLK_ENABLE()    // 按键端口时钟使能宏

/* ---------------------------------------------------------------------------------- */
/* [配置参数区] 软件逻辑相关的参数阈值                                                */
/* ---------------------------------------------------------------------------------- */
#define KEY_TIMEOUT_MS          5000                            // 按键卡死/长按超时阈值 (ms)

/* 语义化键值定义 */
#define KEY_STATE_NONE          0                               // 状态：无按键按下
#define KEY_STATE_PRESSED_1     1                               // 状态：按键 1 已按下并确认
#define KEY_STATE_PRESSED_2     2                               // 状态：按键 2 已按下并确认

/* ---------------------------------------------------------------------------------- */
/* [功能接口声明] 对外公开的应用层 API                                                */
/* ---------------------------------------------------------------------------------- */
void key_init(void);                // 初始化按键 GPIO 配置（内部上拉输入）
uint8_t key_get_active(void);       // 轮询扫描并返回当前激活的键值

#endif /* __KEY_H__ */
